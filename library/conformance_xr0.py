"""Conformance check: run the fine-tuned XR0 checkpoint on one dataset frame and
compare predicted vs target actions (sanity that it's not noisy shaking)."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import torch

from physicalai.data import LeRobotDataModule
from physicalai.data.observation import ACTION, STATE
from physicalai.policies import XR0
from physicalai.train.utils import reformat_dataset_to_match_policy

CKPT = "experiments/xr0_Put-the-yellow-ball-to-the-black-box/checkpoints/last.ckpt"
CHECKPOINT = "/home/devuser/dlyakhov/physical-ai-studio/library/experiments/Put_different_box_10/checkpoints/last.ckpt"
N_ACTION_STEPS = 10  # Match export_xr0_local.py; the IR trims 30 predictions to 10.

DATASET_ROOT = "/home/devuser/dlyakhov/datasets/Put-different-balls-to-the-box"
EPISODE = 3
ACTION_DIM = 6
# Shared with conformance_xr0_ov.py so both pick the *same* shuffled frame
# (same reference target) and the same rectified-flow noise -> fair 1-to-1.
SEED = 0
# Generated by conformance_xr0_ov.py with PIN_NOISE=True.
PAIR_PATH = Path("xr0_conformance_pair.npz")


IMAGE_KEY_VIEW_MAP = {
    "images.top_camera": "ego",
    "images.pov_black_follower_camera": "wrist_left",
}
def main() -> None:
    # Prefer the Intel GPU for a same-machine PyTorch vs OpenVINO comparison.
    device = "xpu" if torch.xpu.is_available() else "cuda" if torch.cuda.is_available() else "cpu"
    print(f"PyTorch inference device: {device}")

    datamodule = LeRobotDataModule(root=str(DATASET_ROOT), data_format="physicalai")
    datamodule.setup("fit")

    hparams = torch.load(CHECKPOINT, map_location="cpu", weights_only=False)["hyper_parameters"]

    policy = XR0(
        pretrained_name_or_path=str(CHECKPOINT),
        dataset_stats=datamodule.train_dataset.stats,
        vlm_attn_implementation="sdpa",
        normalization_mode="MEAN_STD",
        normalize_state=False,
        action_mode="delta",
        n_action_steps=N_ACTION_STEPS,
        image_key_view_map=IMAGE_KEY_VIEW_MAP,
        action_mean=hparams["action_mean"],
        action_std=hparams["action_std"],
    )
    policy.to(device).eval()

    dm = LeRobotDataModule(
        root=DATASET_ROOT,
        train_batch_size=1,
        num_workers=0,
        pin_memory=False,
        episodes=[EPISODE],
        val_split=0.0,
        data_format="physicalai",
    )
    dm.setup("fit")
    reformat_dataset_to_match_policy(policy, dm)

    # Seed the shuffled sampler so we always pull the same frame (identical to
    # conformance_xr0_ov.py).
    torch.manual_seed(SEED)
    batch = next(iter(dm.train_dataloader()))
    target = batch.action[..., :ACTION_DIM].reshape(-1, ACTION_DIM).cpu().numpy()

    if not PAIR_PATH.is_file():
        msg = f"Run conformance_xr0_ov.py with PIN_NOISE=True first to create {PAIR_PATH}"
        raise FileNotFoundError(msg)
    with np.load(PAIR_PATH, allow_pickle=False) as pair:
        ov_pred = pair["pred"].copy()
        ov_raw_action = pair["raw_action"].copy()
        ov_target = pair["target"]
        if not (
            np.array_equal(batch.state[0].cpu().numpy(), pair["state"])
            and np.array_equal(target[: len(ov_target)], ov_target)
        ):
            msg = "The saved OpenVINO result used a different dataset frame; rerun both scripts with the same seed"
            raise ValueError(msg)
        noise = torch.from_numpy(pair["noise"].copy())
        ov_inputs = {
            key: pair[key].copy() for key in ("input_ids", "attention_mask", "pixel_values", "model_state")
        }

    with torch.no_grad():
        # Use exactly the graph inputs and noise from the OpenVINO run; keep
        # image_grid_thw from eager preprocessing (the same fixed image geometry).
        observation = batch.to(policy.device).to_dict()
        processed = policy._preprocessor(observation)  # noqa: SLF001
        valid = int(ov_inputs["attention_mask"].sum())
        eager_ids = processed["input_ids"].cpu().numpy().reshape(-1)
        ov_ids = ov_inputs["input_ids"].reshape(-1)
        print(f"input tokens: eager {len(eager_ids)}, OpenVINO valid {valid}, equal prefix: {np.array_equal(eager_ids, ov_ids[:valid])}")
        eager_pixels = processed["pixel_values"].float().cpu().numpy()
        if eager_pixels.shape != ov_inputs["pixel_values"].shape:
            msg = f"Pixel shapes differ: PyTorch {eager_pixels.shape}, OpenVINO {ov_inputs['pixel_values'].shape}"
            raise ValueError(msg)
        print(f"input pixel max abs difference: {np.abs(eager_pixels - ov_inputs['pixel_values']).max():.6f}")
        for name, key in (("input_ids", "input_ids"), ("attention_mask", "attention_mask"),
                          ("pixel_values", "pixel_values"), ("state", "model_state")):
            processed[name] = torch.from_numpy(ov_inputs[key]).to(policy.device)
        noise = noise.to(device=policy.device, dtype=torch.float32)
        actions = policy.model._run(processed, return_loss=False, noise=noise)  # noqa: SLF001
        pred = policy._postprocessor({ACTION: actions, STATE: observation[STATE]})[ACTION]  # noqa: SLF001
    # Eager _postprocessor keeps all 30 steps; the exported Runtime also trims
    # the chunk to n_action_steps. Compare the steps the robot would execute.
    pred = pred[..., :ACTION_DIM].reshape(-1, ACTION_DIM).cpu().numpy()[: len(ov_pred)]

    raw_action = actions.float().cpu().numpy()
    if raw_action.shape != ov_raw_action.shape:
        msg = f"Raw action shapes differ: PyTorch {raw_action.shape}, OpenVINO {ov_raw_action.shape}"
        raise ValueError(msg)
    if not np.isfinite(raw_action).all() or not np.isfinite(ov_raw_action).all():
        raise ValueError("Raw model action contains NaN or infinity")
    raw_err = np.abs(raw_action - ov_raw_action)
    print(f"raw model OpenVINO vs PyTorch: MAE {raw_err.mean():.4f}   max abs {raw_err.max():.4f}")
    torch_active = raw_action.reshape(-1, raw_action.shape[-1])[:, :ACTION_DIM]
    ov_active = ov_raw_action.reshape(-1, ov_raw_action.shape[-1])[:, :ACTION_DIM]
    active_err = np.abs(torch_active - ov_active)
    print(f"raw active-joint per-dim MAE: {np.round(active_err.mean(0), 4)}")
    for t in (0, torch_active.shape[0] // 2, torch_active.shape[0] - 1):
        print(f"  raw t={t}: OpenVINO {np.round(ov_active[t], 4)}  PyTorch {np.round(torch_active[t], 4)}")

    if pred.shape != ov_pred.shape:
        msg = f"Output shapes differ: PyTorch {pred.shape}, OpenVINO {ov_pred.shape}; check n_action_steps"
        raise ValueError(msg)
    paired_err = np.abs(pred - ov_pred)
    print(f"paired OpenVINO vs PyTorch: MAE {paired_err.mean():.4f}   max abs {paired_err.max():.4f}")

    target = target[: pred.shape[0]]
    err = np.abs(pred - target)
    print(f"pred shape {pred.shape}  target shape {target.shape}")
    print(f"per-dim MAE: {np.round(err.mean(0), 4)}")
    print(f"overall MAE: {err.mean():.4f}   max abs err: {err.max():.4f}")
    for t in (0, target.shape[0] // 2, target.shape[0] - 1):
        print(f"\nt={t}")
        print(f"  target: {np.round(target[t], 4)}")
        print(f"  pred  : {np.round(pred[t], 4)}")


if __name__ == "__main__":
    main()
